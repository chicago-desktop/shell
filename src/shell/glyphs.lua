-- Графические элементы оболочки, собранные в одном месте.
--
-- Символы вынесены из отрисовки нарочно. Рассыпанные по коду, они правятся
-- по одному: кто-то меняет угол рамки в окне и не находит тот же угол в
-- меню, и две детали одной оболочки начинают выглядеть из разных программ.
--
-- ПРАВИЛО ШИРИНЫ. Каждый символ здесь занимает РОВНО ОДНУ ячейку. Символ
-- шириной в две (эмодзи, знаки CJK, ⌚ и подобные «часы») сдвигает всё
-- правее себя на этой строке, и рамка окна разъезжается на каждой строке,
-- где он встретился, — а выглядит это как ошибка арифметики, не как
-- неудачный символ. Проверено по EastAsianWidth: у всего набора класс N или
-- A, то есть одна ячейка везде, кроме восточноазиатской локали. Отсюда же
-- `glyphs.all()` — набор, на котором тест меряет ширину и не пускает
-- широкий символ в набор.
--
-- Объём Windows 95 — это две грани в один пиксель: светлая сверху и слева,
-- тёмная снизу и справа. В ячейку терминала помещается одна грань, поэтому
-- грани разведены по разным ячейкам рамки, а не нарисованы внутри одной.

local glyphs = {}

-- Грани объёмной рамки. Восьмушки блока дают тонкую линию у самого края
-- ячейки — в отличие от половинок (▀ ▄ ▌ ▐), которые заливают её наполовину
-- и превращают рамку в жирную полосу.
glyphs.bevel = {
    top = "▔",      -- верхняя грань
    bottom = "▁",   -- нижняя грань
    left = "▏",     -- левая грань
    right = "▕",    -- правая грань
    -- Углы. В угловой ячейке сходятся две грани, и тонкой линией их не
    -- показать: четвертинки блока — единственная форма, где видно обе.
    corner_light = "▛",   -- светлый угол: верх и лево
    corner_shadow = "▟",  -- тёмный угол: низ и право; он же — ухват размера
}

-- Заливки. `▒` — фон «занятости» и полосы прокрутки, `░` — та самая
-- крапчатая заливка нажатой кнопки Windows 95.
--
-- Половинки блока здесь не для заливки, а ради этчед-разделителя. Настоящий
-- разделитель Windows 95 — две грани в один пиксель, тёмная над светлой; в
-- ячейку терминала помещается одна грань, но не одна ГРАНИЦА: половинка
-- блока красит верх ячейки цветом текста, а низ — цветом фона, и обе
-- грани умещаются в одной строке.
glyphs.shade = {
    light = "░",
    medium = "▒",
    dark = "▓",
    full = "█",
    half_top = "▀",
    half_bottom = "▄",
}

-- Кнопки заголовка. Свернуть — черта у нижнего края, развернуть — пустой
-- квадрат, закрыть — косой крест. Три знака, которые в Windows 95 читаются
-- без подписи.
glyphs.buttons = {
    minimize = "▁",
    maximize = "☐",
    close = "✕",
    -- «Что это?» диалога. Вопрос, а не значок: другого общепонятного знака
    -- у контекстной справки нет.
    help = "?",
}

-- Полоса прокрутки: стрелки на концах, крапчатая дорожка, сплошной бегунок.
glyphs.scrollbar = {
    up = "▲",
    down = "▼",
    left = "◀",
    right = "▶",
    track = "░",
    thumb = "█",
}

-- Значки. Один символ на значок: два уже не влезают в кнопку панели задач
-- рядом с именем окна, а ярлык с обрезанным именем бесполезен.
glyphs.icons = {
    -- Логотип «Пуска». Не флажок из четырёх цветов — в одной ячейке его не
    -- собрать; `⊞` читается как «окна» и держится на любом шрифте.
    start = "⊞",
    program = "▣",       -- программа
    unknown = "▢",       -- программа без своего значка (умолчание из FR)
    folder = "▤",        -- папка меню или стола
    folder_open = "▥",   -- та же папка, раскрытая
    broken = "▨",        -- ярлык на исчезнувшую запись
    clock = "◷",         -- часы на панели задач
    user = "☺",          -- вошедший пользователь в «Пуске»
    submenu = "▸",       -- у пункта есть вложение
    bullet = "▪",        -- маркер строки
    check = "✓",         -- отмеченный пункт
    divider = "─",       -- разделитель в меню
}

-- Полный набор одной таблицей — для теста ширины. Порядок не важен, важно,
-- что ни один символ не остался вне проверки: набор, из которого можно
-- забыть добавить строку, проверяет не то, что нарисовано.
function glyphs.all()
    local out = {}
    for _, group in ipairs({glyphs.bevel, glyphs.shade, glyphs.buttons, glyphs.scrollbar, glyphs.icons}) do
        for _, char in pairs(group) do
            out[#out + 1] = char
        end
    end
    return out
end

return glyphs
